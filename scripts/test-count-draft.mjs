import assert from 'node:assert/strict';
import {build} from 'esbuild';
const b=await build({entryPoints:['src/lib/stockCountDraft.ts'],bundle:true,write:false,platform:'node',format:'cjs'});
const m={exports:{}};new Function('module','exports',b.outputFiles[0].text)(m,m.exports);
const {readCountDraft,writeCountDraft}=m.exports;
const map=new Map(),storage={getItem:k=>map.get(k)??null,setItem:(k,v)=>map.set(k,v),removeItem:k=>map.delete(k)};
const snapshot={ingredient_id:'sugar',name:'Gula',expected_base_unit:'unit',expected_balance:5,expected_version:'v1',counted_quantity:0,display_unit:'pack',display_factor:1};
const draft={entries:{sugar:{input:'0.5',snapshot}},notes:'Weekly count',packMode:false,updatedAt:new Date().toISOString()};
const key='count:owner:draft';
let raw=writeCountDraft(storage,key,draft,null);
assert.deepEqual(readCountDraft(raw),draft);
assert.equal(readCountDraft(storage.getItem('count:other-user:draft')),null);
const next={...draft,entries:{sugar:{input:'0',snapshot}}};
const other=writeCountDraft(storage,key,next,raw);
assert.throws(()=>writeCountDraft(storage,key,draft,raw),/another tab/);
assert.throws(()=>writeCountDraft(storage,key,null,raw),/another tab/);
assert.equal(readCountDraft(other).entries.sugar.input,'0');
raw=writeCountDraft(storage,key,{...draft,entries:{sugar:{input:'0.',snapshot,packs:'',loose:'0.'}}},other);
assert.equal(readCountDraft(raw).entries.sugar.input,'0.','Incomplete typing survives a refresh.');
assert.throws(()=>readCountDraft(JSON.stringify({...draft,entries:{wrong:{input:'1',snapshot}}})),/could not be read/);
assert.throws(()=>readCountDraft(JSON.stringify({...draft,entries:{sugar:{input:'1',snapshot:{...snapshot,display_factor:0}}}})),/could not be read/);
assert.throws(()=>writeCountDraft({...storage,setItem:()=>{}},key,draft,raw),/not saved/);
assert.equal(writeCountDraft(storage,key,null,raw),null);
assert.equal(storage.getItem(key),null);
console.log('PASS: unfinished/zero/fractional entries, snapshot and account isolation, malformed drafts, storage failures, stale-tab write/clear protection, explicit discard.');
