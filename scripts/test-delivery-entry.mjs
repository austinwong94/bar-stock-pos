import assert from 'node:assert/strict';
import { build } from 'esbuild';
async function load(file) {
  const result = await build({entryPoints:[file],bundle:true,write:false,platform:'node',format:'cjs'});
  const module={exports:{}};new Function('module','exports',result.outputFiles[0].text)(module,module.exports);return module.exports;
}
const delivery=await load('src/lib/deliveryEntry.ts');
const {deliveryRemaining,outstandingAfterDelivery,deliveryStockLabel,deliveryPurchaseLabel,suggestedDeliveryEntry}=delivery;
assert.equal(delivery.fillDeliveryRemaining,undefined,'No quantity-copy shortcut is exported');
const items=Array.from({length:50},(_,n)=>({id:`item-${n}`,item_name:`Food ${n}`,unit:'kg',purchase_status:'bought',purchased_quantity:10,purchase_receipts:[{purchase_quantity:2.5}]}));
const ingredients=items.map((i,n)=>({id:`stock-${n}`,name:i.item_name,active:true,base_unit:'g'}));
for(const item of items)assert.equal(suggestedDeliveryEntry(item,ingredients).quantity,'','Purchased quantities are not actual received quantities');
assert.equal(suggestedDeliveryEntry({...items[0],unit:'packet'},ingredients).size,'','Never guess packet contents');
const outstanding=outstandingAfterDelivery(items,[{item_id:'item-0',quantity:3},{item_id:'item-1',quantity:7.5}]);
assert.equal(outstanding.length,49);assert.equal(outstanding.find(r=>r.item.id==='item-0').remaining,4.5);
assert.equal(outstanding.find(r=>r.item.id==='item-2').remaining,7.5,'Unentered purchases stay outstanding');
assert.equal(deliveryRemaining({...items[0],purchased_quantity:0.3,purchase_receipts:[{purchase_quantity:0.1},{purchase_quantity:0.1}]}),0.1);
const weighed={...items[0],purchased_quantity:0.1234,purchase_receipts:[{purchase_quantity:0.02}]};
assert.equal(deliveryRemaining(weighed),0.1034);
assert.equal(outstandingAfterDelivery([weighed],[{item_id:'item-0',quantity:0.1}])[0].remaining,0.0034);
assert.equal(deliveryStockLabel(123.4,'g','kg',1000),'0.1234 kg');
assert.equal(deliveryStockLabel(1250,'g'),'1.25 kg');assert.equal(deliveryStockLabel(4,'unit'),'4 pcs');assert.equal(deliveryStockLabel(500,'ml'),'500 ml');
assert.equal(deliveryPurchaseLabel(2,'kg',1000,'g'),'2 kg');
assert.equal(deliveryPurchaseLabel(3,'packet',500,'g'),'3 packet · 500 g / packet');
const {definitiveInitialSaveFailure}=await load('src/lib/saveAttempt.ts');
assert.equal(definitiveInitialSaveFailure(false,{code:'P0001'}),true);
assert.equal(definitiveInitialSaveFailure(false,{code:'PGRST202'}),true);
assert.equal(definitiveInitialSaveFailure(false,new Error('Lost response')),false);
for(const code of ['42501','40001','P0001','PGRST202'])assert.equal(definitiveInitialSaveFailure(true,{code}),false,'A rejected retry cannot disprove an earlier uncertain save');
console.log('PASS: 50 blank actual quantities, manual partial delivery, precise remaining quantities, kg/pcs/ml, and uncertain-save retries.');
const {deliveryLineError,deliveredStockQuantity}=await load('src/lib/delivery.ts');
assert.equal(deliveryLineError('kg','unit',7,null,10,false,2,12),null);
for(const count of [null,0,-1,1.5,NaN,Infinity])assert.equal(deliveryLineError('kg','unit',7,null,10,false,2,count),'pieces');
assert.equal(deliveryLineError('kg','unit',7,1000,10,false,2,12),'pieces');
assert.equal(deliveryLineError('kg','g',7,1000,10,false,2,12),'unit');
assert.equal(deliveredStockQuantity({quantity:7,base_per_unit:null,measured_pieces:12}),12,'Never derive an average or rounded kg/pcs factor');
assert.equal(deliveryPurchaseLabel(7,'kg',null,'unit'),'7 kg');
assert.equal(suggestedDeliveryEntry({item_name:'Crab',unit:'kg'},[{id:'crab',name:'Crab',active:true,base_unit:'unit'}]).ingredientId,'crab');
console.log('PASS: measured pieces must be explicit, whole and exact; fixed conversions cannot be bypassed.');
