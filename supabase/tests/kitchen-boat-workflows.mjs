import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';

export async function testKitchenBoatWorkflows(db, connect, {owner,cook,tablet}) {
  let passed=0;
  const check=(name,got,want)=>{assert.deepEqual(got,want,name);console.log('PASS',name);passed++;};
  const fail=async(name,task,pattern)=>{await assert.rejects(task,pattern,name);console.log('PASS',name);passed++;};
  const as=async(client,id)=>{await client.query('set role authenticated');await client.query("select set_config('request.jwt.claim.sub',$1,false)",[id]);};
  const value=async(sql,args=[],client=db)=>Object.values((await client.query(sql,args)).rows[0]??{})[0];
  await as(db,owner);
  const date=await value("select to_char(now() at time zone 'Asia/Kuala_Lumpur','YYYY-MM-DD')");
  const bid=await value('select public.save_booking($1::jsonb,$2::jsonb)',[JSON.stringify({service_date:date,lead_name:'Dietary regression',pickup_required:false}),JSON.stringify([{full_name:'Guest Meal Test',age_band:'adult',is_lead:true}])]);
  const tourist=await value('select id from public.tourists where booking_id=$1',[bid]);
  const readMeals=()=>value('select public.read_guest_meal_needs($1)',[date]);
  let guest=(await readMeals()).find(r=>r.tourist_id===tourist);
  check('Unasked allergies are never shown as no allergies',guest.allergy_status,'unknown');
  const details={meal_preference:'vegetarian',allergy_status:'reported',allergens:['Shellfish'],notes:'Separate utensils'};
  const token=randomUUID();
  const save=(version,data=details,key=randomUUID(),client=db)=>value('select public.save_guest_meal_needs($1,$2,$3::jsonb,$4)',[tourist,version,JSON.stringify(data),key],client);
  check('Meal requirements save against the guest',await save(null,details,token),tourist);
  check('Retrying a meal save returns the same result',await save(null,details,token),tourist);
  await fail('An older meal form cannot overwrite a new requirement',()=>save(null),/changed/);
  await as(db,cook);
  guest=(await readMeals()).find(r=>r.tourist_id===tourist);
  check('Kitchen sees vegetarian preference and reported allergen',[guest.meal_preference,guest.allergens],['vegetarian',['Shellfish']]);
  check('Kitchen meal response excludes unrelated private data',['passport','medical_notes','phone'].some(k=>k in guest),false);
  await value('select public.review_guest_meal_needs($1,$2)',[tourist,guest.updated_at]);
  check('Kitchen acknowledgement is attributed',!!(await readMeals()).find(r=>r.tourist_id===tourist).reviewed_by,true);
  await save(guest.updated_at,{...details,notes:'Updated instructions'});
  const changed=(await readMeals()).find(r=>r.tourist_id===tourist);
  check('Changed meal requirements require another kitchen review',changed.reviewed_at,null);
  await fail('A kitchen review cannot acknowledge an older version',()=>value('select public.review_guest_meal_needs($1,$2)',[tourist,guest.updated_at]),/changed/);
  await as(db,tablet);
  await fail('Bar-only staff cannot read guest allergies',()=>readMeals(),/access/i);
  check('Anonymous visitors cannot read meal requirements',await value("select has_function_privilege('anon','public.read_guest_meal_needs(date)','EXECUTE')"),false);

  await as(db,owner);
  const food=await value("insert into public.ingredient_items(name,category,base_unit,default_pack_size,pack_label) values('Kitchen Test Crab','Seafood','unit',10,'Tray') returning id");
  await value("select public.stock_in_ingredient($1,2,'pack',10)",[food]);
  const food2=await value("insert into public.ingredient_items(name,category,base_unit,default_pack_size,pack_label) values('Kitchen Test Squid','Food','g',1000,'Bag') returning id");
  await value("select public.stock_in_ingredient($1,2,'pack',1000)",[food2]);
  await as(db,cook);
  const stock=await value('select public.read_kitchen_stock()');
  check('Kitchen stock view excludes liquor',stock.items.some(i=>i.category==='Liquor'),false);
  const out=(lines,key=randomUUID(),client=db)=>value("select public.record_kitchen_stock_out($1::jsonb,'Spoilage','Damaged during storage',$2)",[JSON.stringify(lines),key],client);
  const line={ingredient_id:food,quantity:2,expected_balance:20,expected_base_unit:'unit'},outToken=randomUUID();
  await out([line],outToken);
  check('Stock-out retry returns the original confirmation',await out([line],outToken),outToken);
  check('Kitchen stock-out deducts once',(await value('select public.read_kitchen_stock()')).items.find(i=>i.id===food).ingredient_balances.quantity_on_hand,18);
  await fail('Pieces cannot be submitted as fractional quantities',()=>out([{...line,quantity:0.5,expected_balance:18}]),/positive quantity/);
  await fail('An old inventory unit cannot change the meaning of stock-out',()=>out([{...line,expected_base_unit:'g'}]),/unit changed/);
  await fail('A stale batch fails without a partial deduction',()=>out([{ingredient_id:food2,quantity:100,expected_balance:2000,expected_base_unit:'g'},line]),/changed/);
  check('Rejected batch preserves other food balances',(await value('select public.read_kitchen_stock()')).items.find(i=>i.id===food2).ingredient_balances.quantity_on_hand,2000);
  const a=await connect(),b=await connect();
  try {
    await as(a,cook);await as(b,cook);
    const race=await Promise.allSettled([out([{...line,expected_balance:18}],randomUUID(),a),out([{...line,expected_balance:18}],randomUUID(),b)]);
    check('Concurrent food stock-outs cannot reuse an old balance',race.filter(r=>r.status==='fulfilled').length,1);
  } finally {await a.end();await b.end();}
  await as(db,tablet);
  await fail('Bar-only staff cannot deduct kitchen food',()=>out([line]),/permission|access/i);

  await as(db,owner);
  await value('select public.ensure_boat_assignments($1)',[date]);
  const assignment=await value('select id from public.boat_assignments where service_date=$1 order by id limit 1',[date]);
  await value('select public.assign_booking_to_boat($1,$2)',[bid,assignment]);
  const getTrip=()=>value('select to_jsonb(t) from public.boat_trips t where assignment_id=$1',[assignment]);
  let trip=await getTrip();
  check('Boat assignment automatically appears as a planned trip',trip.trip_status,'planned');
  check('Planned passengers are distinct from checked-in passengers',[trip.planned_pax,trip.pax_count],[1,0]);
  const totals=()=>value('select trips from public.fuel_period_totals($1,$1)',[date]);
  const beforeTrips=await totals();
  const confirm=(row,status='departed',key=randomUUID())=>value("select public.confirm_scheduled_boat_trip($1,$2,$3,'09:30',$4)",[row.id,row.updated_at,status,key]);
  await fail('Trip departure waits for boarding to be resolved',()=>confirm(trip),/Finish boarding/);
  const boatCode=await value('select code from public.boats where id=$1',[trip.boat_id]);
  check('A planned boat is not reported as an actual trip',(await value('select public.operations_summary($1)',[date])).trips.some(t=>t.boat===boatCode),false);
  const passengers=(await db.query('select id from public.trip_passengers where assignment_id=$1',[assignment])).rows.map(r=>r.id);
  await value("select public.mark_boarding($1::uuid[],'arrived')",[passengers]);
  await fail('Attendance changes invalidate an older departure screen',()=>confirm(trip),/changed/);
  trip=await getTrip();const depToken=randomUUID();
  await confirm(trip,'departed',depToken);
  check('Departure retry returns the existing trip',await confirm(trip,'departed',depToken),trip.id);
  check('Confirmed departure contributes exactly one actual trip',await totals(),beforeTrips+1);
  check('Assignment and trip share departure status',(await getTrip()).trip_status,'departed');
  await fail('An automatic trip cannot be removed as a manual record',()=>value('select public.delete_boat_trip($1)',[trip.id]),/Scheduled/);
  await fail('An automatic trip cannot be overwritten by the manual form',()=>value("select public.save_boat_trip($1,$2,$3,'other')",[trip.id,date,trip.boat_id]),/Scheduled/);
  await confirm(await getTrip(),'returned');
  check('Return updates the same trip without double counting',await totals(),beforeTrips+1);
  check('Completed boat record remains visible',(await getTrip()).trip_status,'returned');
  return passed;
}
