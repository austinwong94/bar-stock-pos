import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';

export async function testGuestPrivacy(db, connect, { owner }) {
  let passed=0;
  const check=(name,got,want)=>{assert.deepEqual(got,want,name);console.log('PASS',name);passed++;};
  const rejects=async(name,task,pattern)=>{await assert.rejects(task,pattern,name);console.log('PASS',name);passed++;};
  const as=async(id,client=db)=>{await client.query('set role authenticated');await client.query("select set_config('request.jwt.claim.sub',$1,false)",[id]);};
  const value=async(sql,args=[],client=db)=>Object.values((await client.query(sql,args)).rows[0]??{})[0];
  const coord='22222222-2222-2222-2222-222222222222', agent='33333333-3333-3333-3333-333333333333';
  await db.query('reset role');
  await db.query("update profiles set access_role_code='coordinator',agency_id=null,status='active' where id=$1",[coord]);
  const today=await value("select ((now() at time zone 'Asia/Kuala_Lumpur')::date)::text");
  const yesterday=await value("select ($1::date-1)::text",[today]);
  const threeDays=await value("select ($1::date-3)::text",[today]);
  await as(owner);
  const id=await value('select save_booking($1::jsonb,$2::jsonb)',[JSON.stringify({service_date:yesterday,lead_name:'Private Test Family',lead_phone:'SECRET-PHONE',lead_email:'secret@example.test',notes:'SECRET-NOTE',pickup_required:true,pickup_hotel_name:'Marina Suites'}),JSON.stringify([{full_name:'Private Test Person',age_band:'adult',is_lead:true,phone:'SECRET-PERSON',private:{passport_no:'SECRET-PASSPORT'}}])]);
  await value('select ensure_boat_assignments($1)',[yesterday]);
  const assignment=await value('select id from boat_assignments where service_date=$1 limit 1',[yesterday]);
  await value('select assign_booking_to_boat($1,$2)',[id,assignment]);
  const original=await value('select to_jsonb(b) from bookings b where id=$1',[id]);
  await value('select admin_save_guest_privacy($1,$2,1,0)',[coord,'contacts']);
  check('Privacy changes record the responsible admin',await value("select actor_id::text from audit_logs where action='guest_privacy_changed' and entity_id=$1 order by created_at desc limit 1",[coord]),owner);
  await as(coord);
  const raw=await value('select count(*)::int from bookings where id=$1',[id]);
  check('Direct REST booking reads cannot bypass expiry',raw,0);
  check('Raw tourist rows are protected after expiry',await value('select count(*)::int from tourists where booking_id=$1',[id]),0);
  check('Raw manifest joins cannot bypass expiry',await value('select count(*)::int from trip_manifest where booking_id=$1',[id]),0);
  const guests=await value('select read_guest_bookings($1)',[yesterday]);
  const guest=guests.find(b=>b.id===id);
  check('Contacts-only rule retains group name',guest.lead_name,'Private Test Family');
  check('Contacts-only rule hides phone',guest.lead_phone,null);
  check('Contacts-only rule hides email',guest.lead_email,null);
  check('Free-text notes cannot disclose contact details',guest.notes,null);
  check('Nested tourist contacts are also hidden',guest.tourists[0].phone,null);
  check('Nested passport record is not returned',guest.tourists[0].tourist_private,null);
  check('Contact-only rule retains passenger totals',guest.pax_total,1);
  const sheet=await value('select read_daily_booking_sheet($1)',[yesterday]);
  check('Sheet declares its privacy state',sheet.contacts_hidden,true);
  check('Sheet contacts are masked at the database',sheet.bookings.find(b=>b.id===id).lead_phone,null);
  const pickup=await value('select read_pickup_board($1)',[yesterday]);
  check('Pickup response cannot recover expired phone',pickup.bookings.find(b=>b.id===id).lead_phone,null);
  const manifest=await value('select read_staff_manifest($1)',[yesterday]);
  check('Controlled manifest retains passenger rows',manifest.some(r=>r.booking_id===id),true);
  check('Controlled manifest hides passenger phone',manifest.find(r=>r.booking_id===id).phone,null);
  check('Expiry begins at the next Malaysia business date',await value("select (guest_privacy($1)->>'contacts_hidden')::boolean",[yesterday]),true);
  check('Today is not hidden prematurely',await value("select (guest_privacy($1)->>'contacts_hidden')::boolean",[today]),false);
  await db.query("set timezone='Pacific/Honolulu'");
  check('Database session timezone cannot shift the cutoff',await value("select (guest_privacy($1)->>'contacts_hidden')::boolean",[yesterday]),true);
  await rejects('Non-admin cannot extend their own access',()=>value('select admin_save_guest_privacy($1,$2,3,1)',[coord,'history']),/access|permission/i);
  await rejects('Non-admin cannot read all privacy settings',()=>value('select admin_guest_privacy()'),/access|permission/i);
  await rejects('Original unmasked helper is not executable',()=>value('select private_guest.read_daily_booking_sheet($1)',[yesterday]),/permission denied/i);
  await rejects('Masked input cannot overwrite original personal data',()=>value('select save_daily_booking($1,$2,$3,$4,$5)',[yesterday,id,original.updated_at,{lead_name:'Private guest'},randomUUID()]),/private/i);
  const log=await value('select read_booking_change_log($1)',[id]);
  check('History keeps attribution without private payloads',log.every(r=>r.details===null),true);
  check('Raw audit payloads cannot bypass privacy',await value('select count(*)::int from audit_logs'),0);
  await as(owner);
  await rejects('Invalid retention days are rejected',()=>value('select admin_save_guest_privacy($1,$2,0,1)',[coord,'contacts']),/1-365/);
  await rejects('A stale admin form cannot replace another edit',()=>value('select admin_save_guest_privacy($1,$2,3,0)',[coord,'contacts']),/another device/);
  await value('select admin_save_guest_privacy($1,$2,3,1)',[coord,'names_contacts']);
  await as(coord);
  check('Three-day rule still permits yesterday',await value("select (guest_privacy($1)->>'contacts_hidden')::boolean",[yesterday]),false);
  check('Three-day cutoff hides the third previous date',await value("select (guest_privacy($1)->>'names_hidden')::boolean",[threeDays]),true);
  await as(owner);
  await value('select admin_save_guest_privacy($1,$2,1,2)',[coord,'names_contacts']);
  await as(coord);
  const masked=(await value('select read_guest_bookings($1)',[yesterday])).find(b=>b.id===id);
  check('Names-and-contacts rule hides group name',masked.lead_name,'Private guest');
  check('Names-and-contacts rule hides every passenger name',masked.tourists.every(t=>t.full_name==='Private guest'),true);
  check('Booking reference remains available for reconciliation',masked.booking_ref,original.booking_ref);
  const meals=await value('select read_guest_meal_needs($1)',[yesterday]);
  check('Kitchen meal response follows guest-name privacy',meals.filter(r=>r.booking_id===id).every(r=>r.full_name==='Private guest'),true);
  await as(owner);
  await value('select admin_save_guest_privacy($1,$2,1,3)',[coord,'history']);
  await as(coord);
  check('Designated in-house PIC can retain original history',await value('select lead_phone from bookings where id=$1',[id]),'SECRET-PHONE');
  await as(owner);
  check('Boss still has original, unchanged name and contacts',await value('select lead_name||lead_phone from bookings where id=$1',[id]),'Private Test FamilySECRET-PHONE');
  await rejects('Agency-linked worker cannot be granted retained history',()=>value('select admin_save_guest_privacy($1,$2,3,0)',[agent,'history']),/cannot retain/i);
  await value("select admin_set_permission_override($1,'guests.finance.manage','grant')",[agent]);
  await as(agent);
  check('Agency worker financial override cannot bypass hard restriction',await value("select has_permission('guests.finance.manage')"),false);
  await rejects('Agency worker cannot retrieve commissions via RPC',()=>value('select read_booking_accounts($1)',[today]),/access|permission/i);
  await as(owner);
  await rejects('Admin form refuses agency financial access',()=>value('select admin_save_guest_privacy($1,$2,1,0,true,false)',[agent,'contacts']),/cannot access/i);
  const planner=randomUUID();
  await db.query('reset role');await db.query("insert into auth.users(id,email,is_anonymous,raw_user_meta_data) values($1,'privacy-planner@test.invalid',false,'{\"full_name\":\"External Planner\"}')",[planner]);
  await db.query("update profiles set status='active',access_role_code='external_planner' where id=$1",[planner]);
  await as(owner);await value('select sheet_planner_access($1,$2,true)',[yesterday,planner]);
  await as(planner);
  const planned=await value('select read_daily_booking_sheet($1)',[yesterday]);
  check('Approved date does not bypass expired names',planned.bookings.find(b=>b.id===id).lead_name,'Private guest');
  await rejects('Planner cannot open booking accounts',()=>value('select read_booking_accounts($1)',[yesterday]),/access|permission/i);
  check('Planner cannot call broader booking read',await value('select read_guest_bookings($1)',[yesterday]),[]);
  await as(owner);
  const a=await connect(),b=await connect();
  try {
    await as(owner,a);await as(owner,b);
    const results=await Promise.allSettled([value('select admin_save_guest_privacy($1,$2,2,4)',[coord,'contacts'],a),value('select admin_save_guest_privacy($1,$2,3,4)',[coord,'names_contacts'],b)]);
    check('Concurrent privacy edits allow exactly one winner',results.filter(r=>r.status==='fulfilled').length,1);
  }finally{await a.end();await b.end();}
  await as(owner);
  await value('select admin_save_guest_privacy($1,$2,1,5)',[coord,'contacts']);
  await value("select admin_set_permission_override($1,'guests.finance.manage','grant')",[coord]);
  await value("select save_booking_finance('account',$1,null,$2,$3)",[id,{amount_due:100,invoice_number:'TEST-INVOICE',remarks:'PRIVATE-ACCOUNT-CONTACT'},randomUUID()]);
  await as(coord);
  const account=(await value('select read_booking_accounts($1)',[yesterday])).accounts.find(a=>a.booking_id===id);
  check('Authorised finance PIC sees figures without private contact notes',account.amount_due,100);
  check('Accounting remarks follow contact expiry',account.remarks,null);
  await rejects('Masked finance notes cannot erase the stored original',()=>value("select save_booking_finance('account',$1,$2,$3,$4)",[id,account.updated_at,{amount_due:120,invoice_number:'TEST-INVOICE',remarks:''},randomUUID()]),/remarks are private/i);
  await as(owner);
  check('Failed masked edit preserves original accounting notes',(await value('select read_booking_accounts($1)',[yesterday])).accounts.find(a=>a.booking_id===id).remarks,'PRIVATE-ACCOUNT-CONTACT');
  return passed;
}
